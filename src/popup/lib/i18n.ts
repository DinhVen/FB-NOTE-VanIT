export type TKey = keyof typeof vi;
export type T = (key: TKey, params?: Record<string, string | number>) => string;

const dicts: Record<Lang, Dict> = { vi, en };

export const createT = (lang: Lang): T => (key, params) => {
  const raw = dicts[lang][key] ?? vi[key] ?? key;
  return params ? raw.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? "")) : raw;
};

export const detectLang = (): Lang => (navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en");
